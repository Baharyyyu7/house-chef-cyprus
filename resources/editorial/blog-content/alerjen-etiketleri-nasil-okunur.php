## Etiket okuma alışkanlıkları

**Her seferinde okuyun.** Üreticiler tarif değiştirir. Aylardır güvenle kullandığınız bir ürünün içeriği yeni partide değişmiş olabilir.

**Tam listeyi okuyun.** Ön yüzdeki "glutensiz" gibi iddialar yararlıdır ama arka yüzdeki tam içerik listesi ve alerjen uyarısı esastır.

**"Doğal aroma" ve "baharat karışımı" gibi genel ifadelere dikkat edin.** Bunlar bileşenlerin ayrıntısını gizleyebilir; emin değilseniz üreticiye sorun.

**Aynı ürünün farklı boyutu farklı olabilir.** Farklı fabrikada üretilmiş olabilir.

## Çapraz bulaşma: evde

Alerjisi olan biriyle aynı mutfağı paylaşıyorsanız:

- **Ayrı doğrama tahtası ve bıçak** kullanın, özellikle gluten ve yemişler için.
- Ekmek kızartma makinesi glutensiz ekmek için ayrı olmalı ya da poşet kullanılmalıdır.
- **Kızartma yağını paylaşmayın**; bir kez balık kızartılan yağ balık proteini taşır.
- Kavanoza aynı bıçakla iki kez daldırmayın (reçel, tereyağı, ezme).
- Alerjenli ürünleri **alt raflarda** saklayın; dökülme yukarıdan aşağı olur.
- Yüzeyleri deterjanla silin; sadece durulamak protein kalıntısını almaz.

