2. Sosların içeriğini ayrıca sorun; sos genellikle unutulur.
3. Kızartmaların ortak yağda yapılıp yapılmadığını sorun.
4. Ciddi alerjiniz varsa bunu net söyleyin; "sevmiyorum" ile "alerjim var" mutfakta farklı işlem görür.

