## Soğan ve patatesi ayırın

Yaygın bir hata, ikisini aynı sepette saklamaktır. Soğan nem verir, patates o nemi alır ve filizlenir. Ayrıca patates etilen üretir, bu da soğanın bozulmasını hızlandırır.

İkisi de karanlık ve serin yer ister ama **ayrı kaplarda** durmalıdır.

## Filizlenen soğan ve sarımsak

Filizlenmiş soğan ve sarımsak **zehirli değildir**, yenebilir. Ancak:

- Filiz, ana ürünün besinini ve nemini kullanır; soğan yumuşar, tadı zayıflar.
- Sarımsakta yeşeren orta filiz belirgin şekilde acıdır. Dişi ikiye bölüp yeşil kısmı çıkarın.

Filizlenen soğanı ilk fırsatta kullanın; filizin kendisi de taze soğan gibi doğranıp kullanılabilir.

Yumuşamış, sulanmış veya küflenmiş olanları atın. Küf görünen kısmı kesip kalanını kullanmak soğanda güvenli değildir; küf hifleri gözle görülenden derine iner.

## Kesilmiş soğan

Kesilmiş soğan artık farklı bir üründür: dokusu açılmıştır, nem kaybeder ve bakteriye açıktır.

- **Kapalı kapta buzdolabında** saklayın, açıkta değil.
- **2-3 gün** içinde tüketin.
- Kokusunun diğer gıdalara geçmemesi için sıkı kapaklı kap kullanın.

"Kesilmiş soğan zehir toplar" şeklindeki yaygın inanışın bilimsel dayanağı yoktur. Ancak kesilmiş soğan, herhangi bir kesilmiş sebze gibi bakteri üremesine uygun bir ortamdır; oda sıcaklığında saatlerce bırakılmamalıdır. Kural karmaşık değil: kapalı kapta, buzdolabında, birkaç gün.

## Sarımsağı uzun süre saklama yolları

**Kavanozda yağda**: Popüler ama riskli bir yöntemdir. Yağda saklanan sarımsak oksijensiz ortam yaratır ve bu ortam *Clostridium botulinum* için uygundur. Ev koşullarında yağda sarımsak saklamak önerilmez. Yapacaksanız buzdolabında ve bir hafta içinde tüketin.

**Dondurma**: Sarımsağı soyup dişler hâlinde veya ezilmiş olarak dondurabilirsiniz. Doku değişir ama tat korunur; pişecek yemekler için sorunsuzdur.

**Kurutma**: Dilimleyip kurutulmuş sarımsak uzun süre dayanır, tozu da yapılabilir.

**Tuzda**: Ezilmiş sarımsağı bol tuzla karıştırıp kavanozda saklamak eski bir yöntemdir. Tuz oranı yüksek olmalı ve yemeğe eklerken tuz hesabı buna göre yapılmalıdır.

## Taze (yeşil) soğan

Kuru soğandan tamamen farklı saklanır. Yeşil soğan yapraklı sebze gibi davranır:

- Buzdolabında, kâğıt havluya sarılı, delikli poşette: 1 hafta.
- Köklerini su dolu bardağa koyup buzdolabında: 1-2 hafta, hatta yeniden uzar.

Ayrıntı için [taze sebzeleri buzdolabında saklamak](/blog/taze-sebzeleri-buzdolabinda-saklamak) yazısına bakabilirsiniz.

## Kokuyu yönetmek

Soğan ve sarımsak kokusu ellerde kalır. Paslanmaz çelik yüzeye (musluk, kaşık) ellerinizi soğuk suyun altında sürtmek kokuyu belirgin biçimde azaltır; kükürtlü bileşikler metalle tepkimeye girer.

Doğrama tahtasında kalan koku için tahtayı limon ve kaba tuzla ovalayın.

