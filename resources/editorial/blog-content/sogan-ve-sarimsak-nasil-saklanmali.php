## Neden buzdolabına girmezler

**Nem.** Buzdolabı nemli bir ortamdır. Soğan ve sarımsak kuru saklanmak üzere evrimleşmiş depolama organlarıdır; nem alan dış kabuk yumuşar, küf başlar.

**Soğuk + nem = filizlenme.** Soğuk, bitkiye "kış bitti, ilkbahar geldi" sinyali verir ve uyku hâlinden çıkmasını tetikler. Nem de bunu destekler. Sonuç: yeşil filiz.

**Koku geçişi.** Soğanın uçucu bileşikleri buzdolabındaki diğer gıdalara, özellikle süt ürünlerine ve yumurtaya geçer.

## Doğru koşullar

