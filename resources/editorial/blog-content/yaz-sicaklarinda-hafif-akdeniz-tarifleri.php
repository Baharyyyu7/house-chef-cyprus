## Sıcakta mutfak stratejisi

### Isıyı güne yay

Fırın ve uzun pişirme gerektiren işleri **sabah erken** yapın. Zeytinyağlıları, haşlanmış bakliyatı, fırın sebzelerini serinken hazırlayıp buzdolabına kaldırın. Akşam yalnız birleştirme kalır.

Bu, Akdeniz'de yaygın bir alışkanlıktır ve zeytinyağlıların soğuk yenmesinin pratik sebeplerinden biridir.

### Ateşi kısalt

Sıcakta uzun pişirme yerine kısa pişirme seçin: sote, ızgara, hızlı tava. Yirmi dakikayı geçen ocak kullanımı yazın gereksizdir.

### Tek kap kullan

Az bulaşık, az ısı. Tek tavada biten yemekler yazın en akılcı seçimdir.

