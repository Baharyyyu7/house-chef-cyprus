## Sıcak havada gıda güvenliği

Yazın kurallar sıkılaşır. Bakterilerin çoğaldığı 5-60°C aralığında geçirilen süre kısalmalıdır.

**Normalde iki saat olan oda sıcaklığı sınırı, hava 32°C üzerindeyse bir saate iner.**

Pratik sonuçlar:

- Piknik ve balkon sofralarında yiyecekleri gölgede ve buzlukta tutun.
- Mayonezli salataları sıcakta bekletmeyin.
- Alışverişten dönüşte soğuk zinciri kırmayın; süt ve et ürünlerini en son alın.
- Artanları hemen soğutun; masada unutulan tencere yazın çok daha risklidir.

Ayrıntı için [artan yemekleri saklama ve ısıtma](/blog/artan-yemekleri-saklama-ve-isitma) yazısına bakabilirsiniz.

## Yaz malzemelerinden en iyi verimi almak

**Domates buzdolabına girmez.** Soğuk, aromasını bozar ve dokusunu unlu yapar. Tezgâhta saklayın.

**Salatalık kabuğunu tamamen soymayın.** Kabuk hem doku hem aroma taşır.

**Otları son anda ekleyin.** Maydanoz, fesleğen ve nane erken eklendiğinde solar ve aroma kaybeder.

**Zeytinyağını ısıtmayın.** Salatada ve mezede sızma zeytinyağının aroması tarifin parçasıdır.

**Karpuz ve peynir birlikte.** Akdeniz'in klasik yaz ikilisi; tuz ve tatlının karşıtlığı sıcakta iyi çalışır.

Sebze saklama hakkında ayrıntı için [taze sebzeleri buzdolabında saklamak](/blog/taze-sebzeleri-buzdolabinda-saklamak) yazısına bakabilirsiniz.

## Bir haftalık yaz çerçevesi

- **Pazar sabahı**: bir tencere nohut haşlayın, iki zeytinyağlı pişirin, bulgur ıslatın.
