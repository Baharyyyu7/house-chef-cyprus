## Sözle verilen ölçüler ne demek

Tariflerde geçen belirsiz ifadelerin pratik karşılıkları:

- **Bir tutam**: iki parmak arasına sığan miktar, yaklaşık 0,3 g. Genellikle tuz ve kuru baharat için kullanılır.
- **Bir çimdik**: tutamdan biraz azı, yaklaşık 0,2 g.
- **Bir demet**: maydanoz, dereotu gibi otlarda elle kavranan miktar; doğranmış hâli yaklaşık 1 su bardağı, ağırlık olarak 30–40 g.
- **Bir diş sarımsak**: 3–5 g, ezildiğinde yaklaşık yarım çay kaşığı.
- **Bir adet orta boy soğan**: 120–150 g, doğranmış hâli yaklaşık 1 su bardağı.
- **Bir paket kabartma tozu**: 10 g, yaklaşık 2 çay kaşığı.
- **Bir paket vanilin**: 5 g.
- **Göz kararı yağ**: tavanın tabanını ince kaplayacak kadar, genellikle 2–3 yemek kaşığı.

## Ne zaman terazi şart

Ev ölçüleri günlük yemeklerin çoğunda yeterlidir. Ama bazı durumlarda tolerans çok dardır:

**Hamur işleri ve ekmek.** Un-su oranı hamurun her şeyidir. %5'lik sapma bile dokuyu değiştirir. Ekmek yapıyorsanız terazi lüks değil, gerekliliktir.

**Pastacılık.** Kek, kurabiye ve özellikle beze gibi tariflerde şeker ve un ağırlığı kimyasal dengeyi kurar. Bardakla yapılan kek "olur" ama tutarlı olmaz — aynı tarif her seferinde farklı çıkar.

**Maya kullanılan her şey.** Maya miktarı gram cinsinden düşüktür ve kaşıkla ölçmek yüksek hata payı taşır.

**Reçel ve şurup.** Şeker-meyve oranı kıvamı ve raf ömrünü belirler.

Buna karşılık şu tariflerde ev ölçüsü fazlasıyla yeterlidir: çorbalar, zeytinyağlılar, pilavlar, sote ve ızgaralar, salatalar. Bu yemeklerde birkaç gramlık sapma sonucu değiştirmez.

## Pilavda ölçü mantığı

Pilav, ev ölçüsünün en iyi çalıştığı yerdir çünkü önemli olan mutlak gram değil, **oran**dır.

- Pirinç pilavı: 1 ölçü pirinç, 1,5 ölçü sıcak su.
- Bulgur pilavı: 1 ölçü bulgur, 2 ölçü sıcak su.
- Şehriyeli pilav: şehriyeyi kavurduktan sonra aynı oranlar geçerli.

Aynı bardağı hem pirinç hem su için kullandığınız sürece hangi bardağı seçtiğiniz önemsizdir. [Zeytinyağlı nohutlu pilav](/tarifler/zeytinyagli-nohutlu-pilav) ve [tavuklu bulgur pilavı](/tarifler/tavuklu-bulgur-pilavi) tarifleri bu oran mantığıyla yazılmıştır.

## Porsiyon değiştirirken ölçüler nasıl davranır

Bir tarifi iki katına çıkarırken her şey ikiye katlanmaz:

- **Doğrusal artanlar**: ana malzemeler, sıvılar, un, şeker.
- **Doğrusal artmayanlar**: tuz ve baharat (genellikle 1,5 kat yeterlidir), maya, pişirme süresi.
- **Hiç artmayanlar**: fırın sıcaklığı.

Süre konusunda sık yapılan hata, miktarı iki katına çıkarınca süreyi de ikiye katlamaktır. Doğrusu, süreyi bir miktar uzatıp iç sıcaklığa veya görsel işarete bakmaktır.

Sitedeki tariflerde porsiyonu değiştirdiğinizde malzeme miktarları otomatik yeniden hesaplanır; ayrıntı için [tariflerde porsiyon ölçekleme](/blog/tariflerde-porsiyon-olcekleme) yazısına bakabilirsiniz.

