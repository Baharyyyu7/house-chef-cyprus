## Neden bir bardak un ile bir bardak şeker aynı gram değil

Ev ölçüleri **hacim** ölçer, tarifler ise çoğu zaman **ağırlık** ister. Aradaki köprü malzemenin yoğunluğudur.

Bir su bardağı (200 ml) şu ağırlıkları taşır:

| Malzeme | Yaklaşık ağırlık |
| --- | --- |
| Su, süt | 200 g |
| Toz şeker | 180 g |
| Un (elenmiş, sıkıştırılmamış) | 120–130 g |
| Un (bardağa bastırılmış) | 150–160 g |
| Pirinç | 180 g |
| Bulgur | 160 g |
| Zeytinyağı | 180 g |
| Kakao | 90 g |
| Ceviz içi (iri) | 100 g |
| Galeta unu | 110 g |

Buradaki en kritik satır un. Aynı bardak, doldurma yönteminize göre 120 g da olabilir 160 g da. Bu %30'luk fark, bir keki kuru, bir hamuru sert yapmaya yeter. Hamur işlerinde başarısızlığın en yaygın sebebi budur.

### Unu doğru ölçmenin yolu

Terazi yoksa şu yöntem farkı büyük ölçüde kapatır:

1. Unu bir kaşıkla havalandırın; paketten doğrudan bardağa daldırmayın.
2. Kaşıkla bardağa **doldurun**, bardağı una daldırmayın.
3. Üstünü bir bıçak sırtıyla düzleyin, asla bastırmayın.
4. Bardağı tezgâha vurmayın; her vuruş unu sıkıştırır.

Bu yöntemle bir su bardağı un tutarlı biçimde 120–130 g arasında kalır.

