Zeytinyağlı sebzeler dondurmaya uygun değildir; çözülünce doku dağılır ve sulanır.

## Yeniden ısıtma

**Tek kural: bir kez ısıtın.** Yemeğin tamamını her seferinde ısıtıp soğutmak, her turda tehlike aralığından geçirir. Yiyeceğiniz kadarını ayırın, kalanı buzdolabında bırakın.

**Sıcaklık hedefi 75°C.** Yemek merkezinden buharı çıkacak kadar, en az iki dakika kaynar veya fokurdar hâlde olmalıdır.

Yönteme göre:

- **Ocak**: Çorba ve sulu yemekler için en iyisi. Arada karıştırın.
- **Fırın**: Fırın yemekleri ve börekler için. 160-180°C, üzeri folyoyla kapalı; son 5 dakika folyoyu açın.
- **Mikrodalga**: Hızlıdır ama eşit ısıtmaz. Yarıda bir durdurup karıştırın, ısıttıktan sonra 1-2 dakika bekletin (ısı dengelensin).
- **Tava**: Pilav ve makarna için. Bir-iki kaşık su ekleyip kapağı kapatın; buhar nemi geri kazandırır.

Dondurulmuş yemeği **buzdolabında çözün**, tezgâhta değil. Acele ediyorsanız mikrodalganın çözdürme programını kullanın ve hemen pişirin.

## Neyi ısıtmamalı

- **Bir kez ısıtılmış yemeği tekrar** ısıtmayın.
- **Oda sıcaklığında dört saatten fazla kalmış** yemeği ısıtmayın, atın.
- **Kokusu, rengi veya dokusu değişmiş** yemeği ısıtmayın. Bu belirtiler yoksa güvenli olduğu anlamına gelmez ama varsa kesin işarettir.
- **Çözülüp tekrar donmuş** yemeği ısıtmayın.

Tereddüt ettiğinizde atın. Bir öğünlük yemeğin maliyeti, bir gıda zehirlenmesinin maliyetinin yanında önemsizdir.

## Artanları yeniden değerlendirmek

Aynı yemeği ikinci gün aynı şekilde yemek zorunda değilsiniz:

- **Artan pilav** → tavada sebzeyle kavurun, üzerine yumurta kırın.
- **Artan tavuk** → didikleyip salataya veya böreğe.
- **Artan sebze yemeği** → blenderdan geçirip çorbaya çevirin.
- **Bayat ekmek** → galeta unu, kruton veya fırında sarımsaklı dilim.
- **Artan et suyu** → buz kalıplarında dondurun, sonraki yemekte kullanın.

Dolabınızdaki artanlarla ne yapabileceğinizi görmek için [Ne Pişirebilirim?](/ne-pisirebilirim) sayfasına malzemelerinizi girebilirsiniz.

