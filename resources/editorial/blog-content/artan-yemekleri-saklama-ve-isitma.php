Bu yazıdaki bilgiler genel gıda güvenliği ilkelerine dayanır ve tıbbi tavsiye değildir. Bağışıklığı baskılanmış kişiler, hamileler, küçük çocuklar ve yaşlılar için daha temkinli davranılmalıdır.

## Tehlike aralığı: 5°C – 60°C

Bakteriler bu sıcaklık aralığında hızla çoğalır. Gıda güvenliğinin tek cümlelik özeti şudur: **yemeği bu aralıkta geçirdiği toplam süreyi kısa tutun.**

Bu, "yemek bozulmuş mu" sorusunun neden yanıltıcı olduğunu da açıklar. Bakteri üremesi çoğu zaman koku, tat veya görünüm değişikliği yaratmaz. Kokusu iyi olan bir yemek güvenli olmayabilir.

## Soğutma: en kritik adım

**İki saat kuralı.** Pişmiş yemek oda sıcaklığında en fazla iki saat kalabilir. Hava 32°C üzerindeyse bu süre bir saate iner.

Tencereyi olduğu gibi buzdolabına koymak yaygın bir hatadır. Büyük ve derin bir tencerede yemeğin ortası saatlerce tehlike aralığında kalır, üstelik buzdolabının iç sıcaklığını yükselterek diğer gıdaları da riske atar.

Doğrusu:

1. Yemeği **sığ kaplara** bölün; derinlik 5-7 cm'i geçmesin.
2. Kapağı açık bırakarak 20-30 dakika soğumaya bırakın.
3. Ilıkken kapağı kapatıp buzdolabına koyun.

Acele ediyorsanız kabı buzlu su dolu bir leğene oturtup arada karıştırın. Bu yöntem soğuma süresini üçte birine indirir.

