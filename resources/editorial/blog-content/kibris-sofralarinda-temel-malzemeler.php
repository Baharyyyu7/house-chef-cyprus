## Hellim

Adanın imza ürünü ve muhtemelen en çok yanlış kullanılan malzemesi.

### Nasıl üretilir, neden erimez

Hellim koyun, keçi ve inek sütünün karışımından yapılır. Pıhtı, peynir altı suyunda yüksek sıcaklıkta haşlanır. Bu işlem protein yapısını sabitler ve peynirin ısıda erimesini engeller. Bu yüzden hellim tavada erimek yerine yumuşar, yüzeyi karamelize olur ve içi lastiğimsi bir esneklik kazanır.

### Taze mi olgun mu

**Taze hellim** yumuşaktır, tuzu düşüktür, ızgara ve tavada kullanılır. Paketinde salamura sıvısı bulunur.

**Olgunlaşmış hellim** sertleşmiştir, tuzu yüksektir, rendelenerek makarnaya ve böreklere gider. Uzun süre saklanabilir.

Markette seçerken salamurası bulanık olmayan, üzerinde sarı lekeler bulunmayan paketleri tercih edin.

### Tuzunu almak

Hellim tuzlu gelirse pişirmeden önce 20-30 dakika soğuk suda bekletin, suyu bir kez değiştirin. Kaynar suya atmayın; doku bozulur.

### Pişirme kuralı

Tavayı iyice ısıtın, çok az yağ kullanın (hellim kendi yağını salar), her yüzü için bir-iki dakika. Kenarları altın rengi olunca alın. Fazla pişen hellim su verir ve sertleşir. [Hellim ve domatesli kahvaltı tavası](/tarifler/hellim-ve-domatesli-kahvalti-tavasi) bu dengeyi öğrenmek için iyi bir başlangıçtır.

## Zeytinyağı

Kıbrıs mutfağında zeytinyağı iki ayrı iş yapar ve bu ikisi karıştırılmamalıdır.

**Pişirme yağı olarak**: soğan kavurmak, sebze soteleme. Burada sızma olmayan, daha nötr bir zeytinyağı yeterlidir ve ekonomiktir.

**Tat malzemesi olarak**: zeytinyağlı yemeklerin üzerine, salataya, mezeye. Burada sızma (natürel sızma) zeytinyağı kullanılır ve ısıtılmaz. Aroması tarifin parçasıdır.

Zeytinyağlı sebze yemeklerinde yağ, sebzenin dokusunu belirler. Az yağla yapılan zeytinyağlı, "diyet" değil eksik olur; yemek soğurken yağın sebzeye sinmesi gerekir. [Zeytinyağlı enginar](/tarifler/zeytinyagli-enginar) bunun tipik örneğidir.

**Saklama**: karanlık, serin yer. Zeytinyağının düşmanı ışık ve ısıdır. Ocağın yanında duran şişe birkaç ayda acılaşır.

## Limon

Kıbrıs sofrasında limon, tuzun yaptığı işin bir kısmını üstlenir; yemeği "açar".

Kullanım zamanlaması önemlidir. Limon suyunun aroması uzun pişmede kaybolur, geriye yalnız asit kalır. Bu yüzden fırın yemeklerinde limonun bir kısmını başta (ete işlemesi için), bir kısmını fırından çıkışta (aroma için) eklemek belirgin fark yaratır.

Limon **kabuğu** ayrı bir malzemedir. Rendelenmiş kabuk uçucu yağ taşır ve tatlılarda, keklerde adaya özgü aromayı verir. Rendelerken beyaz kısma inmeyin; acılık oradan gelir.

## Kişniş tohumu

Kıbrıs mutfağını Türkiye mutfağından ayıran en belirgin baharat budur. Tanesi öğütülmüş hâlinden çok daha aromatiktir.

Kullanmadan önce kuru tavada 30-40 saniye kavurun, sonra havanda kabaca ezin. Bu adım aromayı kat kat artırır. Kişniş özellikle patates, tavuk ve kolokoti gibi tariflerde belirleyicidir.

Öğütülmüş kişniş aldıysanız küçük paket alın; öğütülmüş baharat üç ayda aromasının çoğunu kaybeder.

## Kuru nane ve kekik

Kıbrıs mutfağı taze ot kadar kuru ot kullanır ve bu bir tercih değil, teknik bir seçimdir.

**Kuru nane** yoğurtlu yemeklerin imzasıdır. Taze naneyle aynı şey değildir; kurutulduğunda aroma profili tamamen değişir. Cacıkta kuru nane kullanılır. Nane yağda ısıtılırsa (naneyi eritilmiş tereyağında birkaç saniye ısıtmak) aroması çorbaya çok daha iyi geçer.

**Kekik** fırın yemeklerinin temelidir. Kuru kekiği yemeğin başında ekleyin; aroması yavaş çözünür.

Her iki otu da yağın içine ekleyin, kuru tencereye değil. Aromatik bileşikler yağda çözünür, suda değil.

## Bulgur

Kıbrıs'ta bulgur pirinç kadar merkezidir. İki ana boyu vardır ve karıştırılmamalıdır:

- **Pilavlık (iri) bulgur**: pilav ve dolma içi.
- **Köftelik (ince) bulgur**: köfte, salata, kısır.

Kolokotinin içinde köftelik bulgur kullanılır; pilavlık kullanırsanız iç harç dağılır.

Bulgur pilavında oran 1 ölçü bulgura 2 ölçü sıcak sudur — pirinçten farklıdır. [Tavuklu bulgur pilavı](/tarifler/tavuklu-bulgur-pilavi) tarifinde bu oran uygulanır.

## Kuru üzüm ve tatlı-tuzlu dengesi

Kıbrıs mutfağının şaşırtıcı özelliği, kuru üzümün tuzlu yemeklerde kullanılmasıdır. Kolokotide, flaounada, bazı pilavlarda bulunur.

Bu bir süsleme değil; tuz ve yağın yoğunluğunu dengeleyen bir karşıtlıktır. Kuru üzümü kullanmadan önce 10 dakika ılık suda bekletip süzün; kuru hâliyle eklerseniz iç harcın nemini çeker.

## Bakliyat

Nohut ve mercimek günlük mutfağın temelidir.

**Nohut** mutlaka gece boyu ıslatılır. Islatma suyuna bir çay kaşığı karbonat eklemek kabuğu yumuşatır ve pişme süresini kısaltır. Ancak fazlası tadı bozar.

**Kırmızı mercimek** ıslatma istemez, hızlı pişer, dağılarak çorbaya kıvam verir. [Mercimek çorbası](/tarifler/mercimek-corbasi) bunun en yaygın örneğidir.

Bakliyatın saklanması konusunda ayrıntı için [kuru bakliyat nasıl saklanır](/blog/kuru-bakliyat-nasil-saklanir) yazısına bakabilirsiniz.

## Domates ve biber

Yaz aylarında taze, kışın salça ve konserve. Kıbrıs mutfağı mevsim dışı taze domatese direnir; kışın konserve domates kullanmak, sulu ve tatsız taze domates kullanmaktan iyidir.

Salça eklerken doğrudan sıvıya atmayın. Salçayı yağda 1-2 dakika kavurmak ham tadını alır ve rengini açar. Bu küçük adım pek çok yemekte fark edilir.

