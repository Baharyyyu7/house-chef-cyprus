Bir mutfağı öğrenmenin en hızlı yolu tariflerini ezberlemek değil, malzemelerini tanımaktır. Kıbrıs mutfağı sekiz-on malzeme etrafında döner; bunları anladığınızda tarifleri okumak yerine anlamaya başlarsınız.

