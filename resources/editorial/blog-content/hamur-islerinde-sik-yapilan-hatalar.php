## Ölçü hataları

### Unu bardakla ölçmek

En yaygın ve en belirleyici hata. Bir su bardağı un, doldurma yönteminize göre 120 g da olabilir 160 g da. Bu %30'luk fark bir hamuru yumuşaktan serte taşır.

Terazi yoksa: unu kaşıkla havalandırıp bardağa **doldurun**, bardağı una daldırmayın, üstünü bıçak sırtıyla düzleyin, bardağı tezgâha vurmayın.

Ayrıntı için [ev ölçüleri rehberine](/blog/ev-olculeri-rehberi) bakabilirsiniz.

### Tarife un eklemek

"Hamur elime yapışıyor, biraz daha un atayım" düşüncesi çoğu hamuru bitirir. Yapışkanlık genellikle sorun değil, doğru kıvamın işaretidir. Yoğurdukça glüten gelişir ve yapışkanlık kendiliğinden azalır.

Elinize yapışmasını istemiyorsanız un yerine **birkaç damla yağ** kullanın ya da ellerinizi ıslatın.

## Maya hataları

### Sıcaklık

Maya canlı bir organizmadır ve sıcaklığa duyarlıdır:

| Sıcaklık | Sonuç |
| --- | --- |
| 20°C altı | Çok yavaş çalışır |
| 25-30°C | İdeal |
| 40°C üzeri | Zayıflar |
| 50°C üzeri | Ölür |

Sıvıyı parmağınızla kontrol edin: ılık hissetmeli, sıcak değil. Emin değilseniz vücut sıcaklığını hedefleyin.

### Mayayı tuzla temas ettirmek

Tuz mayayı doğrudan öldürmez ama yüksek yoğunlukta temas onu ciddi biçimde zayıflatır. Tuzu ve mayayı kabın karşıt taraflarına koyun, unu ekledikten sonra karıştırın.

### Ölü maya kullanmak

Paketin tarihi geçmişse veya açıldıktan sonra uzun süre beklediyse maya çalışmayabilir. Test etmek kolaydır: ılık suya bir çay kaşığı şeker ve mayayı ekleyin, 10 dakika bekleyin. Köpürmüyorsa maya ölüdür, hamura koymayın.

### Yetersiz mayalanma

"Bir saat kabarsın" yazan tarifler ortalama koşulu varsayar. Soğuk bir mutfakta iki saat gerekebilir. Süreye değil **hacme** bakın: hamur iki katına çıkmalıdır.

Parmak testi: hamura parmağınızı bastırın. İz yavaşça geri doluyorsa hazırdır. Hemen geri doluyorsa daha zaman ister; hiç dolmuyorsa fazla mayalanmıştır.

## Yoğurma hataları

### Az yoğurmak

Glüten ağı yeterince gelişmezse hamur gazı tutamaz ve kabarmaz. Elle yoğurma 10-15 dakika sürer; makineyle 6-8 dakika.

Hazır olduğunu anlamak için **pencere testi**: küçük bir parça hamuru parmaklarınızla nazikçe gerin. Yırtılmadan ince, ışık geçiren bir zar oluşturabiliyorsa glüten gelişmiştir.

### Fazla yoğurmak

Elle yoğururken neredeyse imkânsızdır; mikserde mümkündür. Fazla yoğrulan hamur yapışkan, gevşek ve kopuk hâle gelir. Bu geri döndürülemez.

### Böreklik hamuru yoğurmak

Her hamur yoğrulmaz. Börek ve poğaça gibi tariflerde amaç glüten geliştirmek değil, tam tersine **azaltmaktır**; fazla yoğrulan börek hamuru sert ve lastikli olur. Bu tariflerde malzemeler sadece birleşene kadar karıştırılır.

Aynı kural kek ve muffin için de geçerlidir: "topaklar kalsın" uyarısı gerçek bir teknik uyarıdır.

## Dinlendirme hataları

Hamurun dinlenmesi, glütenin gevşemesini sağlar. Dinlenmemiş hamur açılırken geri çeker ve yırtılır.

Yufka ve gözleme gibi ince açılan hamurlarda dinlendirme en az 30 dakikadır. Hamuru nemli bezle örtün; açıkta bırakılan hamurun yüzeyi kabuk bağlar ve o kabuk pişince sert bir katman olur.

[Kıbrıs hellimli gözleme](/tarifler/kibris-hellimli-gozleme) gibi tariflerde bu adım atlandığında hamur açılmaya direnir.

## Fırın hataları

### Fırını önceden ısıtmamak

Hamur işlerinde ilk şok ısı belirleyicidir. Soğuk fırına giren hamur, kabarmaya başlamadan yüzeyini kaybeder. Fırını hedeflenen sıcaklığa getirip **en az 15 dakika** daha bekleyin; termostat hedefe ulaştığını söylese de fırının kütlesi henüz ısınmamıştır.

### Sıcaklığa güvenmek

Ev fırınlarının çoğu gösterdiği sıcaklıkta değildir; 20-30°C sapma yaygındır. Ucuz bir fırın termometresi bu belirsizliği ortadan kaldırır.

### Kapağı sık açmak

Her açışta sıcaklık belirgin biçimde düşer. Özellikle ilk 15 dakikada kapağı açmayın; hamur o sırada son kabarmasını yapar.

### Alt-üst ısı ve fan

Fanlı ayarda sıcaklığı 20°C düşürün. Fan, ısıyı hızlı dolaştırdığı için hamurun yüzeyi içi pişmeden kurur.

