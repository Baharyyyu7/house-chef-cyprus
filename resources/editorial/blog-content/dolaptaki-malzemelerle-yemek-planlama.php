## Adım 1: Envanter

Haftada bir kez, on dakika. Üç yere bakın:

- **Buzdolabı**: taze sebze, süt ürünleri, açılmış kavanozlar, artanlar.
- **Kiler/dolap**: bakliyat, makarna, pirinç, konserve, salça.
- **Dondurucu**: et, ekmek, dondurulmuş sebze, önceden pişirilmiş porsiyonlar.

Yazmadan yapmayın. Zihinde tutulan envanter, alışverişte "acaba var mıydı" diye ikinci kez almanıza yol açar.

[Malzeme Dolabım](/dolabim) sayfasına ürünlerinizi son kullanma tarihleriyle kaydederseniz bu envanteri her seferinde yeniden çıkarmanız gerekmez; bitmek üzere olanlar üstte görünür.

## Adım 2: Bozulma sırasına diz

Planın omurgası budur. Malzemeleri ömrüne göre sıralayın ve **kısa ömürlüden başlayarak** pişirin.

| Sıra | Grup | Ne zaman |
