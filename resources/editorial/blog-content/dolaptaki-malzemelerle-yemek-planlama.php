| 4 | Havuç, lahana, patates | 5-7. gün |
| 5 | Bakliyat, makarna, konserve | Her zaman |

Bu sıralama bir menü değil, bir **çerçeve**dir. Salı akşamı ne yiyeceğinizi belirlemez; salatalığın çarşambaya kalmayacağını söyler.

## Adım 3: Ortak malzemeyi çoğalt

Bir malzemeyi bir kez hazırlayıp birden fazla öğünde kullanmak, plan yapmanın en verimli hâlidir.

Örnekler:

- **Bir tavuk pişirin** → ilk gün fırın tavuk, ikinci gün didiklenmiş tavuklu salata, üçüncü gün kemiklerden çorba suyu.
- **Büyük bir tencere nohut haşlayın** → bir gün nohutlu pilav, bir gün humus, bir gün salataya.
- **Bir kap soğan kavurun** → çorbaya, kıymalı yemeğe, böreğin içine.

Bu yöntem "meal prep" gibi zorlayıcı değildir; tek fark, pişirirken bir sonraki öğünü düşünmektir.

## Adım 4: Boşlukları belirle

Envanter ve çerçeve elinizdeyken alışveriş listesi kısalır. Yalnız **eksik olan bağlayıcıları** alırsınız: bir kutu domates, bir demet maydanoz, bir paket yoğurt.

Bu, alışveriş faturasını görünür biçimde düşüren tek değişikliktir.

## Esnek plan, katı plan değil

Haftanın her öğününü belirlemek çoğu evde tutmaz; bir akşam plan değişir ve zincir kırılır. Daha dayanıklı yöntem şudur:

- **Üç sabit öğün** belirleyin (yoğun günler için).
- **İki esnek gün** bırakın (elde ne kaldıysa).
- **Bir gün dışarıda/artan** için ayırın.

Bu yapı, planın bir kez bozulduğunda tamamen çökmesini önler.

## Elindekilerle ne yapabileceğini görmek

Envanteri çıkardıktan sonra en zor kısım "bu malzemelerle ne olur" sorusudur.

[Ne Pişirebilirim?](/ne-pisirebilirim) sayfasına elinizdeki malzemeleri yazdığınızda:

- Tam yapabileceğiniz tarifler,
- Alternatif malzemeyle yapabilecekleriniz,
- Tek malzeme eksik olanlar

ayrı ayrı listelenir. Eksik olanları görmek, alışveriş listesini de kendiliğinden oluşturur.

Üye iseniz dolabınızı doğrudan eşleştirmeye dahil edebilirsiniz.

## Dondurucuyu takas alanı gibi kullanın

Bozulmak üzere olan bir malzemeyi pişirmeye vaktiniz yoksa dondurun:

- Ekmek dilimlenip dondurulur, tostluk olarak doğrudan kullanılır.
- Taze otlar doğranıp buz kalıbında zeytinyağıyla dondurulur.
- Fazla domates rendelenip dondurulur, sosa gider.
- Pişmiş bakliyat porsiyonlanıp dondurulur.

Bu, planı bozmadan zaman kazanmanın en pratik yoludur.

## Haftalık ritim önerisi

- **Pazar**: envanter + 20 dakikalık hazırlık (bakliyat haşlama, sebze doğrama).
- **Hafta içi**: kısa ömürlüden uzuna doğru ilerleyin.
- **Cuma**: "temizlik günü" — artanlarla omlet, makarna veya çorba.
- **Cumartesi**: serbest.

Cuma temizlik günü fikri basit ama etkilidir: haftanın artıklarını tek öğünde toplar ve buzdolabını yeni haftaya boş girmeye hazırlar.

Artanların güvenli saklanması için [artan yemekleri saklama ve ısıtma](/blog/artan-yemekleri-saklama-ve-isitma), sebzelerin ömrünü uzatmak için [taze sebzeleri buzdolabında saklamak](/blog/taze-sebzeleri-buzdolabinda-saklamak) yazılarına bakabilirsiniz.
