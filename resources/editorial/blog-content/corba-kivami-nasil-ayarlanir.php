Çorbanın kıvamı, tadı kadar belirleyicidir. Fazla sulu bir çorba tatsız algılanır, çünkü aroma molekülleri seyrelmiştir; fazla koyu bir çorba ise ağırlaşır. İyi haber, kıvamın her aşamada düzeltilebilir olmasıdır.

## Kıvam nereden gelir

Çorbaya kıvam veren dört mekanizma vardır ve hangisini kullandığınız sonucu belirler:

1. **Nişasta jelleşmesi** — un, nişasta, patates, pirinç, mercimek.
2. **Emülsiyon** — yağ ve sıvının birleşmesi; terbiye bu gruba girer.
3. **Püre** — katı malzemenin ezilmesi.
4. **Buharlaşma** — sıvının azalması; en yavaş ama en lezzet yoğunlaştırıcı yöntem.

## Koyulaştırma yöntemleri

### Un (meyane)

En klasik yöntem. Ancak unu doğrudan çorbaya atmak topaklanmaya yol açar; un suya değdiği anda dışı jelleşir ve içi kuru kalır.

Doğru yol:

1. Küçük bir tavada 1 yemek kaşığı tereyağını eritin.
2. 1 yemek kaşığı unu ekleyip **orta ateşte 2 dakika** kavurun. Bu adım unun ham tadını alır.
3. Bir kepçe **sıcak** çorba suyunu azar azar ekleyip çırpın.
4. Pürüzsüz karışımı çorbaya dökün, 5 dakika kaynatın.

Bir yemek kaşığı un, yaklaşık 1 litre çorbayı belirgin biçimde koyulaştırır.

### Nişasta

Mısır nişastası una göre daha berrak bir sonuç verir ve daha güçlüdür. Mutlaka **soğuk suda** ezilir, sonra çorbaya eklenir. Sıcak sıvıya doğrudan atılan nişasta anında topaklanır.

Nişasta uzun kaynatmada kıvamını kaybeder; eklendikten sonra 2-3 dakika kaynatıp ateşten alın.

### Püre

En sağlıklı ve en doğal yöntem. Çorbanın bir kısmını alıp blenderdan geçirin ve geri ekleyin. Un veya nişasta katmadan kıvam kazanırsınız, üstelik tadı seyreltmezsiniz.

Mercimek, patates, kabak ve nohut bu yöntemle çok iyi çalışır. [Mercimek çorbası](/tarifler/mercimek-corbasi) zaten dağılan mercimek sayesinde kendi kıvamını kurar.

### Ekmek içi

Akdeniz mutfağının eski yöntemi. Bayat ekmek içi çorbaya eklenip ezilir. Hem kıvam verir hem israfı önler.

## İnceltme

Çorba fazla koyu olduysa:

- **Sıcak su veya et suyu** ekleyin. Soğuk sıvı eklemek çorbanın sıcaklığını düşürür ve nişastalı çorbalarda topaklanmaya yol açabilir.
- Su yerine **et/tavuk suyu** kullanmak tadı seyreltmez.
- Ekledikten sonra tuzu yeniden değerlendirin; sıvı arttıkça tuz oranı düşer.

## Terbiye: en çok sorun çıkaran adım

Terbiye, yoğurt-yumurta-un karışımının çorbaya eklenmesidir. Doğru yapıldığında ipeksi bir doku verir; yanlış yapıldığında kesilir ve çorbada tanecikler yüzer.

### Neden kesilir

Yoğurt ve yumurta protein içerir. Proteinler ani ısıda pıhtılaşır. Soğuk terbiyeyi doğrudan kaynar çorbaya eklerseniz protein anında pıhtılaşır — yani kesilir.

### Kesilmeden eklemenin yolu

**Temperleme** denen bu işlem şöyledir:

1. Bir kapta yoğurt, yumurta sarısı ve unu pürüzsüz olana kadar çırpın.
2. Çorbadan bir kepçe sıcak suyu **ince bir şerit hâlinde** dökerken sürekli çırpın.
3. Bunu 3-4 kepçe daha tekrarlayın. Terbiye artık çorbayla aynı sıcaklığa yaklaşmıştır.
4. Ilınmış terbiyeyi çorbaya dökün, karıştırın.
5. **Kaynatmayın.** Terbiyeli çorba kaynarsa yine kesilir. Fokur fokur değil, hafif buğulanacak kadar ısıtın.

Un eklemek terbiyeyi stabilize eder; unsuz terbiye çok daha kolay kesilir.

### Kesilirse

Blenderdan geçirmek görünümü büyük ölçüde kurtarır. Doku eskisi kadar ipeksi olmaz ama servis edilebilir hâle gelir.

