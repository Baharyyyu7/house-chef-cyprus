## Sık yapılan hatalar

**Unu doğrudan atmak.** Topaklanır. Meyane yapın veya soğuk suda ezin.

**Terbiyeyi temperlemeden eklemek.** Kesilir.

**Terbiyeli çorbayı kaynatmak.** Kesilir.

**Soğuk su ile inceltmek.** Isıyı düşürür, topaklanma riski yaratır.

**Kıvamı sıcakken değerlendirmek.** Çorba soğudukça koyulaşır. Servis kıvamından biraz daha sulu bırakın.

