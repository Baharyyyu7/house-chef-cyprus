## Eski bakliyat neden pişmez

Zamanla tanenin kabuğundaki hücre duvarlarında kimyasal değişim olur ve kabuk suya geçirimsizleşir. Bu olguya bazen "sert tohum" denir. Sonuç: tane su alamaz, kaynasa da yumuşamaz.

Bu geri döndürülemez. Üç yıllık bir nohut, ne kadar ıslatırsanız ıslatın taze nohut gibi pişmez.

### Kurtarma yöntemleri

Tamamen çaresiz değilsiniz:

- **Karbonat**: Islatma suyuna 1 litreye yarım çay kaşığı karbonat ekleyin. Alkali ortam kabuğu yumuşatır. Fazlası tadı sabunumsu yapar ve B vitaminlerini bozar.
- **Uzun ıslatma**: 12 saat yerine 18-24 saat, suyu iki kez değiştirerek.
- **Düdüklü tencere**: Basınç, normal kaynamanın çözemediği kabuğu açar. Eski bakliyat için en etkili yöntem budur.
- **Tuzu sona bırakın**: Tuz, pişme sırasında kabuğu sertleştirir. Bakliyat yumuşadıktan sonra tuzlayın.

Sert su da pişmeyi zorlaştırır. Suyunuz çok kireçliyse ıslatma ve pişirme için filtre edilmiş su kullanmak fark yaratır.

## Böceklenme

Bakliyat böceği (özellikle *baklagil biti*) genellikle markete gelmeden önce yumurtasını tanenin içine bırakır. Yani ev koşulları kusursuz olsa bile böcek çıkabilir.

### Önleme

- **Dondurma**: Yeni aldığınız bakliyatı kapalı poşette 3-4 gün derin dondurucuda tutun. Bu, yumurtaları öldürür ve en etkili yöntemdir.
- **Defne yaprağı**: Kavanoza 2-3 defne yaprağı koymak caydırıcıdır. Bilimsel olarak kesin bir koruma değildir ama zararı yoktur ve halk arasında yaygındır.
- **Küçük paket almak**: Bir-iki aylık tüketiminiz kadar alın; uzun süre bekleyen bakliyat her zaman daha risklidir.
- **Düzenli kontrol**: Ayda bir kavanozları gözden geçirin. Bir kavanozdaki böcek diğerlerine geçer.

### Böcek çıkarsa

Küçük miktarda böcek gördüyseniz bakliyatı su dolu kaba boşaltın; böcekli ve boş taneler yüzeye çıkar, onları alın. Ancak yoğun böceklenme varsa atın ve dolabı sirkeli suyla silin, komşu paketleri de kontrol edin.

## Pişirmeden önce

**Ayıklama**: Bakliyatı açık renkli bir tepsiye yayıp taş, toprak parçası ve kırık taneleri ayıklayın. Bu adım özellikle kuru fasulye ve nohutta gereklidir.

**Yıkama**: Berrak su gelene kadar durulayın.

**Islatma**: Nohut ve kuru fasulye gece boyu (8-12 saat) ıslatılır. Islatma suyunu dökün; bu su, gaz yapan oligosakkaritlerin bir kısmını taşır.

Kırmızı mercimek ıslatma istemez, doğrudan pişer. [Mercimek çorbası](/tarifler/mercimek-corbasi) bu yüzden en hızlı yapılabilen sıcak yemeklerden biridir.

Nohutlu tarifler için [zeytinyağlı nohutlu pilav](/tarifler/zeytinyagli-nohutlu-pilav) ve [fırın nohut](/tarifler/firin-nohut) sayfalarına bakabilirsiniz.

## Pişmiş bakliyatı saklamak

Pişmiş bakliyat buzdolabında 3-4 gün, derin dondurucuda 2-3 ay durur. Suyuyla birlikte dondurursanız doku daha iyi korunur.

Pratik bir yöntem: bir seferde çok miktarda nohut haşlayıp porsiyonlar hâlinde dondurmak. Böylece nohutlu bir yemek, konserve almadan on beş dakikada hazırlanabilir hâle gelir.

