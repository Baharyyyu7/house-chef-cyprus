## Üç düşman: nem, ısı, ışık

**Nem** en tehlikelisidir. Bakliyat higroskopiktir, yani havadaki nemi çeker. Nem oranı yükseldiğinde küf riski başlar ve tanenin dokusu bozulur.

**Isı** yaşlanmayı hızlandırır. 25°C üzerinde saklanan bakliyat, serin yerde saklanana göre çok daha çabuk "pişmez" hâle gelir.

**Işık** rengi soldurur ve besin değerini bir miktar düşürür.

İdeal koşul: karanlık, serin (15-20°C), kuru bir dolap. Ocağın üstündeki dolap ya da bulaşık makinesinin yanı en kötü yerlerdir.

## Doğru kap

Bakliyatı geldiği poşette bırakmayın. Poşetler hava ve nem geçirir, ayrıca böcek için kolay hedeftir.

En iyisi **cam kavanoz**, kapağı sıkı kapanan. Cam koku almaz, nem geçirmez ve içeriği görmenizi sağlar. Plastik kaplar da işe yarar ancak gıda sınıfı ve sızdırmaz olmalıdır.

Kavanozu doldurmadan önce tamamen kuru olduğundan emin olun. Yıkanmış ve tam kurumamış bir kavanoz, içindeki bakliyatı birkaç haftada küflendirir.

