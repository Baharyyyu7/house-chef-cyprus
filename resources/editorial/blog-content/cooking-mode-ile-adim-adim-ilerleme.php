## Önce mise en place

Fransızca "her şey yerinde" demek olan bu terim, profesyonel mutfakların temel disiplinidir ve evde de en çok fark yaratan alışkanlıktır.

Pişirmeye başlamadan önce:

1. Tarifi **baştan sona bir kez okuyun**. Sürprizleri önceden görün.
2. Bütün malzemeleri çıkarın ve ölçün.
3. Doğrama işlerini bitirin, küçük kaplara ayırın.
4. Kullanacağınız kap ve aletleri hazırlayın.
5. Fırın gerekiyorsa şimdi ısıtmaya başlayın.

Bu on dakika, pişirme sırasında telaşla geçirilen yirmi dakikayı ortadan kaldırır. Ayrıca "soğan kavrulurken sarımsağı doğrayayım" gibi zamana sıkışan işleri bitirir — ki o telaş, yanmış soğanın en yaygın sebebidir.

## Adım işaretleme

Tarif sayfalarındaki yapım adımlarında her adımın numarası aynı zamanda bir **işaretleme düğmesi**dir. Tamamladığınız adıma dokunduğunuzda:

- Adım soluklaşır ve başlığı üstü çizili olur,
- Üstteki sayaç "3 / 7 adım" olarak güncellenir,
- İlerleme çubuğu dolar.

İşaretlediğiniz adımlar **bu cihazda saklanır**. Sayfayı yenileseniz, telefonu kilitleyip açsanız veya sekmeyi kapatıp geri dönseniz kaldığınız yer durur. Giriş yapmanız gerekmez ve sunucuya hiçbir veri gönderilmez.

Yeniden başlamak için "Sıfırla" düğmesi yeterlidir.

## Zamanlayıcı kullanımı

Aynı anda birden fazla iş yürüyorsa hafızaya güvenmeyin. Pratik kural: **iki dakikadan uzun her bekleme için zamanlayıcı kurun.**

Birden fazla zamanlayıcıya ihtiyaç duyduğunuzda her birine ne olduğunu yazın ("makarna", "fırın", "dinlenme"). İsimsiz üç alarm çaldığında hangisinin ne olduğunu hatırlamak zordur.

Sitedeki Cooking Mode ekranında adım bazlı zamanlayıcılar vardır; süre içeren adımlarda doğrudan başlatılabilir.

## Ekranla çalışmanın pratik düzeni

**Telefonu dik tutun.** Tezgâha yatık bir telefon hem görülmez hem ıslanır. Basit bir stand veya bardağa yaslamak yeterlidir.

**Ekranı açık tutun.** Cihazınızın otomatik kilit süresini uzatın; elleriniz hamurluyken ekran açmak zordur.

**Sesli okuma kullanabilirsiniz.** İşletim sisteminin ekran okuma özelliği, elleriniz meşgulken adımı dinlemenizi sağlar.

**Ekranı korumak için**: telefonu şeffaf bir poşete koymak eski ama etkili bir çözümdür.

## Zamanlamayı planlamak

Çoğu tarif tek bir zaman çizgisiymiş gibi yazılır ama gerçekte paralel işler vardır. Pişirmeye başlamadan önce şunu belirleyin:

- **En uzun süren iş hangisi?** Onunla başlayın.
- **Bekleme süreleri nerede?** O boşluklara kısa işleri yerleştirin.
- **Ne son anda yapılmalı?** Salata sosu, taze ot, ızgara peynir.

Örnek: fırın tavuk pişerken salata doğranır, sos hazırlanır, sofra kurulur. Tavuk dinlenirken salata karıştırılır.

## Sık yapılan hatalar

**Tarifi okumadan başlamak.** "Bir gece önceden ıslatın" satırını pişirmeye başladıktan sonra görmek yaygın bir hayal kırıklığıdır.

**Ölçmeyi pişirirken yapmak.** Ateş yanarken ölçü almak hata oranını yükseltir.

**Bütün adımları aynı anda takip etmeye çalışmak.** Tek adıma odaklanın; işaretleme tam da bunun için var.

**Zamanlayıcı yerine "aklımda tutarım" demek.** Mutfakta dikkat sürekli bölünür.

## Yeni başlayanlar için sıra

İlk kez yaptığınız bir tarifte:

1. Tarifi bir gün önce okuyun.
2. Eksik malzemeyi önceden alın.
3. Mise en place'ı acele etmeyin.
4. İlk seferde tarifi değiştirmeyin; önce olduğu gibi yapın, sonra kendinize uyarlayın.
5. Not alın: süre yetti mi, tuz yeterli miydi, fırınınız nasıl davrandı?

Bu notlar ikinci seferde tariften daha değerli olur, çünkü sizin mutfağınızı yansıtır.

