## Üç değişken: sıcaklık, nem, etilen

**Sıcaklık.** Soğuk, çoğu sebzede solunumu yavaşlatır ve ömrü uzatır. Ama tropik kökenli sebzelerde soğuk hasarı yaratır: domates, salatalık, patlıcan, biber düşük sıcaklıkta doku ve aroma kaybeder.

**Nem.** Yapraklı sebzeler nem ister, soğan ve sarımsak nemden çürür. Buzdolabının sebzelik çekmecesindeki nem ayarı tam da bunun içindir.

**Etilen.** Bazı meyveler etilen gazı üretir, bu gaz komşularının olgunlaşmasını hızlandırır. Yanlış eşleştirme, sebzelerin günler yerine saatler içinde bozulmasına yol açar.

