## Buzdolabına girmeyecekler

**Domates.** 12°C altında aroma molekülleri bozulur ve doku unlu hâle gelir. Bu değişim geri döndürülemez. Tezgâhta, sap tarafı aşağıda saklayın. Çok olgunlaştıysa buzdolabı ömrü uzatır ama tadı zaten düşmüştür.

**Patates.** Soğukta nişasta şekere dönüşür; patates tatlanır ve kızartıldığında koyu renk alır. Karanlık, serin, havadar bir yerde saklayın. Işık gördüğünde yeşillenir — yeşillenen kısımlar solanin içerir ve kesilip atılmalıdır.

**Soğan ve sarımsak.** Nemden çürür, filizlenir. Kuru ve havadar yer isterler. Ayrıntı için [soğan ve sarımsak nasıl saklanmalı](/blog/sogan-ve-sarimsak-nasil-saklanmali) yazısına bakabilirsiniz.

**Bal kabağı ve kabuklu kabaklar.** Bütün hâlde oda sıcaklığında haftalarca durur. Kesildikten sonra buzdolabına girer.

**Sarımsak ve soğanı patatesle birlikte saklamayın**; soğanın nemi patatesin filizlenmesini hızlandırır.

## Buzdolabına girecekler ve nasıl

### Yapraklı sebzeler (marul, ıspanak, roka, maydanoz)

En çabuk bozulan gruptur ve en çok kazanç sağlayan gruptur.

Yöntem:
1. Yıkamayın (kullanmadan hemen önce yıkayın). Islak yaprak çürür.
2. Kuru bir kâğıt havluyla sarın.
3. Delikli poşete veya kapaklı kaba koyun.
4. Sebzelik çekmecesine kaldırın.

Kâğıt havlu fazla nemi emer ve yaprakların birbirine yapışmasını önler. Havlu ıslanınca değiştirin. Bu yöntemle marul 3-4 gün yerine 7-10 gün dayanır.

Maydanoz ve dereotu için alternatif: sapları su dolu bir bardağa koyup üzerini poşetle örtün, buzdolabına kaldırın. Çiçek gibi düşünün.

### Havuç, kereviz, turp

Yeşil sapları varsa kesin; yapraklar kökten nem çeker ve sebze pörsür. Kapalı kapta, hafif nemli saklayın. Havuç bu yöntemle haftalarca dayanır.

### Brokoli, karnabahar

Delikli poşette, sebzelik çekmecesinde. Yıkamayın. Etilene duyarlıdır, meyvelerden uzak tutun.

### Salatalık, biber, patlıcan

Buzdolabının en soğuk yerine koymayın; kapı rafı veya sebzelik çekmecesinin üst kısmı daha uygundur. Salatalık 10°C altında yumuşar ve sulanır. Poşetlemeyin, hava alsın.

### Taze fasulye, bezelye

Delikli poşette, 3-5 gün. Uzun saklama için haşlayıp (blanching) dondurun.

