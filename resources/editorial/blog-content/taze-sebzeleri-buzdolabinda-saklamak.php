## Kesilmiş sebzeler

Kesilen sebze çok daha hızlı bozulur; kesik yüzey hem nem kaybeder hem mikroorganizmaya açılır.

- Kesilmiş sebzeleri kapalı kapta, buzdolabında, **1-2 gün** içinde tüketin.
- Kesilmiş soğanı kapalı kapta saklayın; kokusu tüm dolaba geçer.
- Kesilmiş avokado ve patlıcanın kararmasını limon suyu yavaşlatır.

