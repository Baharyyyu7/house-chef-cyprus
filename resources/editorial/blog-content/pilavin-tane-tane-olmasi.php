Pilav, az malzemeyle yapıldığı için hata affetmeyen yemeklerden biridir. Lapa olmuş bir pilavın sebebi neredeyse her zaman dört şeyden biridir: nişasta, su oranı, ısı yönetimi ya da demlenme. Bu yazı her birini ayrı ayrı ele alıyor, böylece kendi mutfağınızdaki sorunun nerede olduğunu bulabilirsiniz.

## Sorunun kaynağı: nişasta

Pirinç tanesinin dışında serbest nişasta bulunur. Bu nişasta suya karıştığında jelleşir ve taneleri birbirine yapıştırır. Tane tane pilavın birinci şartı, bu serbest nişastanın pişirmeden önce uzaklaştırılmasıdır.

### Yıkama

Pirinci geniş bir kapta soğuk suyla yıkayın. İlk suyun rengi süt gibi bulanık çıkar. Elinizle nazikçe karıştırıp suyu dökün ve bunu **su berraklaşana kadar** tekrarlayın; genellikle 3-5 defa yeterlidir.

Pirinci ovalamayın. Sert ovalama taneleri kırar, kırık taneler pişerken dağılır ve tam da kaçındığınız lapayı yaratır.

### Bekletme

Yıkadıktan sonra pirinci ılık ve tuzlu suda 20-30 dakika bekletmek iki iş yapar: kalan nişastayı çözer ve taneyi eşit ısıtır, böylece pişerken bazı taneler diğerlerinden önce dağılmaz.

Bekletme suyunu mutlaka dökün ve pirinci süzün. Bu suyu pişirmede kullanırsanız çözdüğünüz nişastayı geri koymuş olursunuz.

## Su oranı

Ölçüyü doğru tutmanın yolu gram değil, **oran**dır. Aynı bardağı hem pirinç hem su için kullandığınız sürece hangi bardağı seçtiğiniz önemsizdir.

| Tahıl | Oran (tahıl : sıvı) |
| --- | --- |
| Baldo, osmancık pirinç | 1 : 1,5 |
| Pirinç (bekletilmemiş) | 1 : 1,75 |
| Pilavlık bulgur | 1 : 2 |
| Basmati | 1 : 1,5 |

Bekletilmiş pirinç zaten su almıştır; bu yüzden bekletmezseniz suyu biraz artırmanız gerekir. Bu ayrıntı çoğu tarifte yazılmaz ve lapa/kuru pilav arasındaki farkın önemli bir kısmını açıklar.

Sıvıyı **sıcak** ekleyin. Soğuk su eklemek tencerenin sıcaklığını düşürür, pişme eşitsizleşir ve dış taneler dağılırken içtekiler diri kalır.

## Isı yönetimi

Pilavın pişme eğrisi üç aşamalıdır ve her aşamada ısı farklıdır.

1. **Kavurma (orta ateş)**: Pirinci yağda 2-3 dakika, tane şeffaflaşıp hafif inci rengi alana kadar çevirin. Bu adım tanenin dışını yağla kaplar ve nişastanın suya geçişini yavaşlatır. Atlanırsa pilav yapışkan olur.
2. **Kaynama (yüksek ateş, kısa)**: Sıcak sıvıyı ekleyin, bir taşım kaynatın.
3. **Pişme (en kısık ateş, kapak kapalı)**: Suyu çekene kadar, 12-15 dakika. Bu aşamada **kapağı açmayın ve karıştırmayın**. Her karıştırma taneleri sürtüştürüp nişasta açığa çıkarır.

Suyun çekilip çekilmediğini anlamak için tencereyi hafifçe eğin; kenarda su birikmiyorsa hazırdır.

## Demlenme: en çok atlanan adım

Ateşi kapattıktan sonra tencerenin kapağı ile pilav arasına temiz bir mutfak bezi koyun ve kapağı kapatıp **10-15 dakika dinlendirin**.

Bu adım süs değil. Pişme bittiğinde tanelerin içindeki nem dağılımı eşit değildir; dış taraf ıslak, iç taraf daha kurudur. Demlenme sırasında nem tane içinde dengelenir ve bez, kapakta yoğunlaşan buharın geri damlamasını engeller. Demlenmemiş pilav servis edildiğinde alt tarafı ıslak kalır.

Dinlenme bitince pilavı kaşıkla karıştırmayın; **çatalla, alttan üste doğru kabartın**.

## Tencere seçimi

Kalın tabanlı tencere ısıyı eşit dağıtır ve dip tutmayı azaltır. İnce tabanlı tencerede alt taneler yanarken üsttekiler pişmemiş kalır.

Tencere boyutu da önemlidir: pirinç tabanı 2-3 cm kalınlığında kaplamalıdır. Çok geniş tencerede su çabuk buharlaşır, çok dar tencerede alt kısım ezilir.

## Sık yapılan altı hata

**Pirinci yıkamamak.** En yaygın sebep. Paket üzerinde "yıkamaya gerek yoktur" yazsa bile yıkayın.

**Bekletme suyunu kullanmak.** Çözülen nişastayı geri koyar.

**Soğuk su eklemek.** Pişmeyi eşitsizleştirir.

**Pişerken karıştırmak.** Her karıştırma nişasta açığa çıkarır.

**Kapağı erken açmak.** Buhar kaçar, su hesabı bozulur.

**Demlendirmemek.** Nem dengelenmez, alt taraf ıslak kalır.

