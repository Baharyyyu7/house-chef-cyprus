## Terazisiz tutarlılık

Terazi almak istemiyorsanız, ev ölçüsünü daha güvenilir hâle getirmenin yolları var.

### Kendi bardağınızı bir kez ölçün

"Su bardağı" standart bir birim değildir; evden eve 180-220 ml arasında değişir. Bardağınıza su doldurup bir kez tartın. Bu tek ölçüm, bütün tariflerinizi kalibre eder.

### Unu her zaman aynı yöntemle ölçün

Hangi yöntemi seçtiğiniz, tutarlı olmanız kadar önemli değildir:

1. Unu kaşıkla havalandırın.
2. Kaşıkla bardağa doldurun.
3. Üstünü bıçak sırtıyla düzleyin.
4. Bardağı tezgâha vurmayın.

Her seferinde aynı yöntemi uygularsanız sapma tekrarlanabilir hâle gelir — ve tekrarlanabilir sapma, tarifi bir kez ayarladıktan sonra sorun olmaktan çıkar.

### Oran düşünün

Mutlak miktar yerine oranla düşünmek ev ölçüsünün gücünü ortaya çıkarır:

- Pilav: 1 tahıl : 1,5 sıvı (pirinç) veya 1 : 2 (bulgur)
- Basit hamur: 3 un : 2 sıvı (hacimce)
- Salata sosu: 3 yağ : 1 asit
- Şerbet: 2 şeker : 1 su (yoğun), 1 : 1 (hafif)

Bu oranlar ezberlendiğinde tarif okumadan yemek yapabilirsiniz.

### Referans noktaları kurun

Elinizle tahmin etmeyi öğrenmek için birkaç referans:

- Avuç içi kadar et ≈ 100 g
- Baş parmak boyu tereyağı ≈ 15 g
- Bir yumurta ≈ 50 g
- Kapalı avuç dolusu makarna ≈ 80-100 g (bir porsiyon)

## Terazi almanın maliyeti

Dijital mutfak terazisi, mutfaktaki en ucuz ekipmanlardan biridir ve en çok fark yaratanlardan biridir. Hamur işi yapıyorsanız yatırımın karşılığı ilk haftada alınır.

Terazi kullanırken pratik ipucu: kabı teraziye koyup **dara** alın, malzemeyi doğrudan içine tartın. Böylece ayrı ölçü kabı yıkamazsınız ve birden fazla malzemeyi aynı kaba sırayla tartabilirsiniz.

