## Ev ölçüsü neden yaygınlaştı

**Her evde vardır.** Terazi bir ekipmandır, bardak zaten mutfaktadır.

**Aktarılabilir.** Bir tarif anneden kıza, komşudan komşuya sözle geçer. "İki su bardağı un" akılda kalır, "240 gram un" kalmaz.

**Oranla çalışır.** Türk mutfağının pek çok temel tarifi mutlak miktar değil oran üzerine kuruludur. Pilavda önemli olan pirincin gramı değil, pirinç-su oranıdır. Aynı bardağı ikisi için de kullandığınız sürece hangi bardağı seçtiğiniz önemsizdir.

Bu üçüncü madde, ev ölçüsünün en güçlü olduğu yerdir ve çoğu zaman gözden kaçar.

## Ev ölçüsünün zayıf olduğu yer

Ev ölçüsü **hacim** ölçer, tarifler bazen **ağırlık** ister. Aradaki köprü yoğunluktur ve yoğunluk malzemeye göre çok değişir.

Bir su bardağı (200 ml):

- Su: 200 g
- Toz şeker: 180 g
- Un: 120-160 g (doldurma yöntemine göre)
- Kakao: 90 g

Undaki %30'luk oynaklık, ev ölçüsünün asıl zayıf noktasıdır. Aynı tarifi aynı bardakla iki kez yapıp iki farklı sonuç almanızın sebebi genellikle budur.

