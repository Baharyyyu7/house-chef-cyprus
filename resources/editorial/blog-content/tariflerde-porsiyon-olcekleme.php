Dört kişilik bir tarifi sekiz kişiye çıkarmak, her malzemeyi ikiye katlamak değildir. Bazı malzemeler doğrusal artar, bazıları artmaz, bazıları hiç değişmez. Bu farkı bilmemek, ölçeklenen tariflerin neden "aynı olmadığını" açıklar.

## Üç davranış grubu

### Doğrusal artanlar

Bunlar güvenle çarpılır:

- Ana malzemeler: et, sebze, tahıl, bakliyat
- Un, şeker, yağ
- Su, süt, et suyu gibi sıvılar
- Yumurta (ama tam sayıya yuvarlanır)

Bir tarifte 3 yumurta varsa ve 1,5 kat ölçekliyorsanız 4,5 yumurta çıkar. Bu durumda 4 yumurta + 1 sarı kullanmak, 5'e yuvarlamaktan daha doğrudur.

### Yarı doğrusal artanlar

Bunlar çarpanın tamamı kadar artmaz:

| Malzeme | 2 kat tarifte |
| --- | --- |
| Tuz | 1,5-1,75 kat |
| Kuru baharat | 1,5 kat |
| Taze ot | 1,5-2 kat |
| Acı biber, pul biber | 1,5 kat |
| Sarımsak | 1,5 kat |
| Maya | 1,5 kat |
| Kabartma tozu | 1,5-1,75 kat |
| Vanilya, esans | 1,5 kat |

Sebep, algının doğrusal olmamasıdır: tuz ve baharat konsantrasyonu iki katına çıktığında algılanan yoğunluk iki kattan fazla artar. Ayrıca daha büyük bir tencerede karışım daha homojen dağılır.

**Doğru yaklaşım**: baharatı 1,5 katla başlatın, pişme sonunda tadıp ekleyin. Eklemek kolaydır, çıkarmak imkânsızdır.

### Hiç değişmeyenler

- **Fırın sıcaklığı**: Asla değişmez. İki kat malzeme için sıcaklığı yükseltmek dışın yanmasına yol açar.
- **Ocak ateşi seviyesi**: Aynı kalır (tencere boyutu değişir).
- **Dinlendirme süresi**: Hamur dinlenmesi, et dinlenmesi ölçekle artmaz.

## Pişirme süresi

En çok hata yapılan alan burasıdır. Süre ölçekle **doğrusal artmaz**.

Sebep basit: pişme, ısının malzemenin merkezine ulaşmasıdır ve bu mesafeye bağlıdır, hacme değil. Bir tepsi yerine iki tepsi sebze pişirirseniz süre neredeyse aynıdır. Ama tek bir parçayı iki katına çıkarırsanız (1 kg yerine 2 kg et) süre uzar, ancak iki katı kadar değil.

Pratik kurallar:

- **Aynı kalınlık, daha fazla parça** → süre neredeyse aynı, belki %10-20 uzar.
- **Daha kalın tek parça** → süre uzar ama %50-70 kadar, iki kat değil.
- **Sıvı yemekler (çorba, sos)** → kaynama süresi biraz uzar, pişirme süresi benzer.

Her durumda süreye değil, **işarete** bakın: iç sıcaklık, kıvam, renk. [Fırın yemeklerinde sıcaklık ve süre](/blog/firin-yemeklerinde-sicaklik-ve-sure) yazısında iç sıcaklık hedefleri var.

## Kap boyutu

Ölçeklerken sık atlanan değişken.

**Çok küçük kap**: Malzeme sıkışır, buhar çıkamaz, kızarma yerine haşlama olur. Fırın sebzelerinde en yaygın hata budur.

**Çok büyük kap**: Sıvı fazla yüzey alanına yayılır, hızlı buharlaşır, yemek kurur.

Kural: malzeme yüksekliği orijinal tarifle benzer olmalıdır. İki katına çıkarıyorsanız, aynı yükseklikte iki kat yüzey alanı gerekir — yani iki tepsi ya da bir büyük tepsi.

Kek ve börek gibi kalıp isteyen tariflerde kalıp hacmini hesaplayın. 20 cm yuvarlak kalıp yerine 26 cm kullanırsanız hacim yaklaşık 1,7 kat artar, yani tarifi 1,7 katla ölçeklemelisiniz.

## Tarifi küçültmek

Yarıya indirmek, büyütmekten daha zordur:

- **Yumurta bölünmesi**: 3 yumurtalı tarifi yarıya indirince 1,5 yumurta çıkar. Yumurtayı çırpıp yarısını tartın (bir yumurta yaklaşık 50 g).
- **Küçük miktarlar ölçülemez**: Yarım çay kaşığının yarısı pratikte tahmindir. Terazi burada daha da önemlidir.
- **Kap boyutu**: Küçültülen tarif büyük tencerede kurur. Kabı da küçültün.
- **Süre kısalır**: Az miktar daha çabuk pişer; süreyi kısaltıp erken kontrol edin.

