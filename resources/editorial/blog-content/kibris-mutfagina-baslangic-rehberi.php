## Kıbrıs'ın imza yemekleri ve neden özel oldukları

### Şeftali kebabı

İsmine rağmen şeftaliyle ilgisi yoktur. Kuzu kıymasının, koyunun karın zarına (gömlek yağı) sarılarak ızgarada pişirilmesiyle yapılır. Zar pişerken erir ve içteki kıymayı hem yağlar hem korur. Bu yüzden dışı gevrek, içi son derece sulu kalır. Evde yapmak istiyorsanız kasaptan zar ayrıca istenmelidir. [Kıbrıs usulü şeftali kebabı](/tarifler/kibris-usulu-seftali-kebabi) tarifi ev koşullarına uyarlanmış hâlidir.

### Kolokoti

Bal kabağı, bulgur, kuru üzüm ve bazen ceviz ile hazırlanan iç harcın, zeytinyağlı bir hamura sarılmasıyla yapılır. Sonbahar yemeğidir; bal kabağının mevsimiyle doğrudan bağlıdır. Tatlı-tuzlu dengesi Kıbrıs mutfağının en ayırt edici örneklerinden biridir.

### Flaouna

Paskalya çöreği olarak bilinir ama bugün yıl boyunca yapılır. İçinde özel bir peynir karışımı, kuru üzüm ve mahlep bulunur; üzerine susam serpilir. Hazırlığı uzundur, bu yüzden genellikle kalabalık için toplu yapılır.

### Molehiya

Kurutulmuş molehiya yaprağıyla pişirilen, kıvamı yoğun bir yemektir. Tadı belirgindir ve ilk denemede herkese hitap etmeyebilir; ancak adada en çok "ev yemeği" sayılan tabaklardan biridir.

## Kıbrıs sofrası nasıl kurulur

Ada mutfağının en önemli özelliği tek bir ana yemek etrafında değil, **paylaşılan küçük tabaklar** etrafında kurulmasıdır. Meze kültürü burada dekoratif bir başlangıç değil, öğünün kendisidir.

Pratik bir ev sofrası şöyle kurulur:

1. **İki soğuk**: cacık ve bir zeytinyağlı.
2. **Bir peynir**: ızgara veya taze hellim.
3. **Bir sıcak hamur işi**: gözleme ya da börek.
4. **Bir ana yemek**: fırın tavuk veya ızgara.
5. **Ekmek ve limon**: masadan hiç eksilmez.

Bu yapıyı kurduğunuzda öğün, tek bir tarifin başarısına bağlı olmaktan çıkar. Bir tabak beklediğiniz gibi olmasa bile sofra ayakta kalır — ki bu, yeni başlayanlar için en değerli güvenliktir.

## Mevsim ritmi

Kıbrıs mutfağı mevsime sıkı bağlıdır ve bu bağ, tarifleri doğru zamanda denediğinizde tadın neden daha iyi olduğunu açıklar.

- **İlkbahar**: enginar, bakla, taze soğan, flaouna dönemi.
- **Yaz**: domates, biber, patlıcan, kabak; ağır fırın yemekleri geri çekilir, salata ve ızgara öne çıkar.
- **Sonbahar**: bal kabağı ve kolokoti zamanı; nar ve incir sofraya girer.
- **Kış**: kuru bakliyat, çorbalar, fırın yemekleri; [mercimek çorbası](/tarifler/mercimek-corbasi) gibi tabaklar günlük hâle gelir.

## Yeni başlayanların en sık yaptığı dört hata

**Hellimi fazla pişirmek.** Hellim ısıda önce yumuşar, sonra su verir, en sonunda sertleşir. Her yüzü için bir-iki dakika yeterlidir. Tavayı iyice ısıtın, hellimi az yağla koyun ve kenarları altın rengi olunca alın.

**Zeytinyağlıyı sıcak servis etmek.** Zeytinyağlı yemekler oda sıcaklığında ya da soğuk yenir. Sıcakken tadı henüz oturmamıştır; birkaç saat dinlenmesi tarifin parçasıdır.

**Limonu sona bırakmamak.** Limon suyu uzun pişmede aromasını kaybeder. Fırın yemeklerinde bir kısmını başta, bir kısmını çıkışta eklemek belirgin fark yaratır.

**Kuru baharatı yağsız eklemek.** Kekik ve kişnişin aroması yağda çözünür. Baharatı kuru tencereye değil, yağın içine ekleyip birkaç saniye ısıtmak tadı ikiye katlar.

