## Nereden başlamalı: zorluk sırasına göre üç aşama

Kıbrıs mutfağına girmenin en hızlı yolu, en meşhur yemekle değil, en affedici yemekle başlamaktır.

### Birinci hafta: tavada ve tencerede

İlk denemeleriniz hamur işi olmasın. Hamur, ölçü ve dinlendirme hatalarını affetmez; ilk denemede moral bozar.

- [Hellim ve domatesli kahvaltı tavası](/tarifler/hellim-ve-domatesli-kahvalti-tavasi) — hellimin nasıl davrandığını öğrenmek için en kısa yol. Tek tavada, on beş dakikada biter.
- [Cacık](/tarifler/cacik) — yoğurt, salatalık, sarımsak ve kuru nane dengesini kurmayı öğretir. Kıbrıs sofrasının neredeyse her öğününde bulunur.
- [Çoban salata](/tarifler/coban-salata) — doğrama boyutunun tada nasıl etki ettiğini gösteren en basit alıştırma.

### İkinci hafta: fırın ve zeytinyağlılar

- [Kıbrıs usulü fırın tavuk](/tarifler/kibris-usulu-firin-tavuk) — limon, kekik ve patatesin fırında birlikte çalışması. Ada mutfağının pazar sofrası mantığını en iyi bu yemek anlatır.
- [Zeytinyağlı enginar](/tarifler/zeytinyagli-enginar) — zeytinyağlıların soğuk servis edildiğini ve tadın dinlendikçe oturduğunu öğreten yemek.

