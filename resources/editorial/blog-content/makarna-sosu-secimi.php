## Temel kural: yüzey ve yoğunluk

Sos, makarnanın **yüzeyine tutunur**. Dolayısıyla eşleştirmenin mantığı şudur:

- **İnce, akışkan soslar** → uzun ve ince makarnalar. Sos ipliklere film gibi sarılır.
- **Yoğun, parçalı soslar** → kısa, oyuklu, kıvrımlı makarnalar. Parçalar oyuklara sıkışır.
- **Çok yoğun, etli soslar** → geniş şeritli makarnalar. Ağırlığı taşıyacak yüzey gerekir.

Ters eşleştirme her zaman aynı sonucu verir: sos tabağın dibinde kalır, makarna kuru gelir.

