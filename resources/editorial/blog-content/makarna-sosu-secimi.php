## Haşlama suyu: en çok atlanan malzeme

Makarna suyu nişasta içerir ve bu nişasta bir **emülsiyon yapıcıdır** — yani yağ ile suyun birbirine karışmasını sağlar. Sos ile makarnayı gerçekten birleştiren şey budur.

Makarnayı süzmeden önce mutlaka **bir bardak suyunu ayırın**. Sos kuruysa, ayrışıyorsa veya tutunmuyorsa iki-üç kaşık makarna suyu ekleyip karıştırın; sos anında bağlanır ve ipeksi bir doku kazanır.

Bu tek alışkanlık, ev makarnası ile restoran makarnası arasındaki farkın önemli bir kısmıdır.

## Suyu tuzlamak

Makarna suyu belirgin biçimde tuzlu olmalıdır. Makarna pişerken tuzu içine alır; sonradan üzerine tuz atmak aynı sonucu vermez, yalnız yüzeyi tuzlar.

Ölçü: 1 litre suya yaklaşık 7-10 g tuz. Su kaynadıktan sonra tuzlayın.

Suya yağ eklemeyin. Yaygın inanışın aksine yapışmayı önlemez; sadece makarnanın yüzeyini kaplayıp **sosun tutunmasını engeller**. Yapışmayı önleyen şey yeterli su ve ilk dakikada karıştırmaktır.

## Al dente neden önemli

"Diş kesecek kadar" pişmiş makarna sadece bir doku tercihi değildir. Makarna sosla birleştirildikten sonra pişmeye devam eder; tam pişmiş olarak süzülen makarna, tabağa geldiğinde fazla pişmiş olur.

Pratik yöntem: paket üzerindeki süreden **1-2 dakika önce** süzün, sonra sosun içinde bir-iki dakika daha pişirin.

## Birleştirme tekniği

Makarnayı tabağa koyup üzerine sos dökmek, en yaygın ve en zayıf yöntemdir. Doğrusu:

1. Sosu geniş bir tavada hazır bekletin.
2. Makarnayı al dente süzün (suyundan bir bardak ayırmayı unutmayın).
3. Makarnayı **sosun içine** alın, tavayı ateşte tutun.
4. Bir-iki kaşık makarna suyu ekleyip 30-60 saniye karıştırın.
5. Ateşten alıp peynir veya taze ot ekleyin.

Bu son aşamada makarna sosu emer; ayrı duran iki bileşen tek bir yemek hâline gelir.

## Peynir zamanlaması

Rendelenmiş peyniri kaynar sosa atmayın; ipleşir ve topaklanır. Ateşten aldıktan sonra ekleyip karıştırın. Kalan ısı peyniri eritmeye yeter.

## Yaygın hatalar

**Az su.** Makarna geniş bir tencerede, bol suda pişmeli. Az suda nişasta yoğunlaşır ve makarnalar yapışır.

**Suyu tamamen dökmek.** Nişastalı su, sosun bağlayıcısıdır.

**Suya yağ eklemek.** Sosun tutunmasını engeller.

**Fazla pişirmek.** Sosla birlikte pişmeye devam edeceğini hesaba katın.

**Sosu tabakta eklemek.** Makarna sosu emmez, sos dibe çöker.

**Sıcak sosa peynir atmak.** İpleşir.

