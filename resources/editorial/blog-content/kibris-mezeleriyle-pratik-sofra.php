## Ne önceden hazırlanır

Meze kültürünün en pratik yanı budur.

**Bir gün önce yapılabilir:**
- Zeytinyağlı sebzeler (dinlendikçe tadı oturur, tarifin gereğidir)
- Humus ve ezmeler
- Turşu, közlenmiş biber
- Hamur (buzdolabında dinlenir)

**Aynı gün, birkaç saat önce:**
- Cacık (çok erken yapılırsa salatalık su salar)
- Börek ve gözleme (pişirilip ısıtılır)
- Peynir tabağı

**Son anda:**
- Salatalar (erken karıştırılırsa söner)
- Izgara hellim (sıcak servis edilmeli)
- Kızartmalar

## Kalabalık için zaman planı

Sekiz kişilik bir sofra için pratik bir plan:

**Bir gün önce**
- Zeytinyağlıları pişirin, buzdolabına kaldırın.
- Hamuru yoğurup dinlendirin.
- Turşu ve zeytinleri kaseye alın.

**Sabah**
- Gözlemeleri pişirin, üst üste koyup örtün.
- Sebzeleri doğrayın, ayrı kaplarda buzdolabında bekletin (salatayı karıştırmayın).
- Cacığın salatalığını rendeleyip suyunu süzün, yoğurtla karıştırmayın.

**Bir saat önce**
- Cacığı birleştirin.
- Zeytinyağlıları buzdolabından çıkarın (oda sıcaklığında servis edilir).
- Masayı kurun.

**On beş dakika önce**
- Salatayı karıştırın, sosunu son anda ekleyin.
- Gözlemeleri ısıtın.

**Servis anında**
- Hellimi ızgarada pişirin ve sıcak getirin.

Bu plan mutfakta geçirdiğiniz süreyi misafir gelmeden önceye taşır.

## Servis düzeni

Kıbrıs sofrasında mezeler **aynı anda** masaya gelir; sırayla değil. Yine de bir düzen vardır:

- Soğuklar masanın merkezinde, herkesin uzanabileceği yerde.
- Sıcaklar kenarlarda, tazeliği korunacak şekilde.
- Ekmek birden fazla noktada; tek sepet uzaktakileri zorlar.
- Limon dilimleri ayrı bir tabakta, her yerden ulaşılabilir.

Küçük tabaklar kullanın. Meze kültüründe amaç doyurmak değil, çeşit denemektir; büyük tabaklar ilk tabakta doyurur.

## Miktar hesabı

Kişi başı yaklaşık ölçüler:

- Kremsi mezeler: 60-80 g
- Salata: 100 g
- Zeytinyağlı: 80 g
- Peynir: 50 g
- Hamur işi: 1-2 parça

Sekiz kişilik sofra için altı çeşit meze, toplamda yaklaşık 3-3,5 kg yiyecek demektir. Meze sofralarında artan olması normaldir ve artanların çoğu ertesi gün de iyidir — saklama için [artan yemekleri saklama ve ısıtma](/blog/artan-yemekleri-saklama-ve-isitma) yazısına bakabilirsiniz.

## Sık yapılan hatalar

**Çok fazla çeşit.** On iki tabak hazırlamaya çalışmak hem yorucudur hem kaliteyi düşürür. Altı iyi tabak, on iki vasat tabaktan iyidir.

**Hepsinin kremsi olması.** Cacık, humus, yoğurtlu patlıcan aynı sofrada olursa denge kurulmaz. Asit ve gevreklik şart.

**Zeytinyağlıyı sıcak servis etmek.** Oda sıcaklığında yenir; sıcakken tadı oturmamıştır.

**Salatayı erken karıştırmak.** Tuz ve sos, sebzeden su çeker; on beş dakikada söner.

**Hellimi erken pişirmek.** Soğuyunca sertleşir. Servis anında pişirilmeli.

## Vejetaryen sofra

Kıbrıs meze kültürü doğal olarak sebze ağırlıklıdır; vejetaryen bir sofra kurmak zorlama gerektirmez. Yukarıdaki altı tabaklık örnekte et zaten yok. Peyniri de çıkarırsanız vegan sofra için humus, zeytinyağlılar, salatalar ve zeytin yeterli bir temel oluşturur.
