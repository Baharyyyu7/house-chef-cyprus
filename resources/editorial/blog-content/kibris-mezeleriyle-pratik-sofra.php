Bu yazı, meze sofrasını evde uygulanabilir hâle getiriyor.

## Meze mantığı: neden işe yarar

Tek ana yemek etrafında kurulan bir öğün, o yemeğin başarısına bağlıdır. Bir şey ters giderse öğün zayıflar.

Meze sofrasında ise **risk dağıtılmıştır**. Sekiz tabaktan biri beklediğiniz gibi olmasa bile sofra ayakta kalır. Yeni başlayanlar için bu, mutfakta kazanılabilecek en büyük güvencedir.

İkinci avantaj: mezelerin çoğu **önceden hazırlanır** ve soğuk servis edilir. Misafir geldiğinde mutfakta olmazsınız.

## Dengeli bir sofranın bileşenleri

İyi bir meze sofrası çeşit sayısıyla değil, **denge**yle kurulur. Beş eksen vardır:

1. **Kremsi**: cacık, humus, yoğurtlu bir şey
2. **Asitli/taze**: çoban salata, turşu, limonlu bir sebze
3. **Yağlı/doyurucu**: zeytinyağlı bir sebze, peynir
4. **Sıcak/gevrek**: ızgara hellim, börek, kızartma
5. **Tuzlu/keskin**: zeytin, tuzlu peynir, turşu

Her eksenden en az bir tabak olduğunda sofra "tamam" hissi verir. Altı tabakla kurulan dengeli bir sofra, on iki tabakla kurulan dengesiz bir sofradan daha iyidir.

